#!/usr/bin/env python3
"""Generate config/companies.yaml from research/source_inventory.json (the 114 verified rows)."""
import json
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DIRECT = {"greenhouse", "ashby", "lever", "rippling", "workday"}
USABLE = {"VERIFIED", "PARTIAL"}
# Corrections found after the 2026-08-20 research probe: company → (ats, slug, note)
OVERRIDES = {
    "Temporal": ("ashby", "temporal", "moved from greenhouse/temporaltechnologies (404) to Ashby; verified 2026-09-23"),
    "Amplitude": ("ashby", "amplitude", "moved from greenhouse/amplitude (404) to Ashby; verified 2026-10-29"),
    "Hightouch": ("ashby", "hightouch", "moved from greenhouse/hightouch (404) to Ashby; verified 2026-10-29"),
}

# Companies added after the research probe: (name, tier, ats, slug, note)
EXTRA = [
    ("SoFi", "tier3", "greenhouse", "sofi", "greenhouse / VERIFIED — added 2026-10-29 (from jobhunter's top_companies)"),
]
# Other spellings used by aggregators (Simplify, Getro, speedyapply, …), so their rows get the company's tier.
ALIASES = {
    "Meta": ["Meta Platforms", "Facebook"],
    "Google": ["Google DeepMind", "DeepMind", "Alphabet", "YouTube"],
    "Amazon": ["Amazon Web Services", "AWS", "Amazon Web Services (AWS)", "Amazon.com"],
    "Microsoft": ["Microsoft AI", "Microsoft Research"],
    "NVIDIA": ["Nvidia Corporation"],
    "Jane Street": ["Jane Street Capital"],
    "Hudson River Trading": ["HRT", "Hudson River Trading (HRT)"],
    "Optiver": ["Optiver US"],
    "Perplexity AI": ["Perplexity"],
    "Cognition AI": ["Cognition"],
    "Mistral": ["Mistral AI"],
    "Runway ML": ["Runway"],
    "Modal Labs": ["Modal"],
    "Scale AI": ["Scale"],
    "Anduril": ["Anduril Industries"],
    "Palantir": ["Palantir Technologies"],
    "Databricks": ["Databricks Inc"],
    "SpaceX": ["Space Exploration Technologies"],
    "Flatiron Health": ["Flatiron"],
}


def slugify(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def main() -> None:
    rows = json.loads((ROOT / "research/source_inventory.json").read_text())
    rows += [{"company": n, "tier": t, "ats": a, "slug": sl, "status": "VERIFIED", "note": note.split(" — ", 1)[1]}
             for n, t, a, sl, note in EXTRA]
    companies = []
    for r in rows:
        c = {"id": slugify(r["company"]), "name": r["company"], "tier": r["tier"]}
        if r["company"] in ALIASES:
            c["aliases"] = ALIASES[r["company"]]
        ats, status = r["ats"], r["status"]
        if r["company"] in OVERRIDES:
            ats, r["slug"], r["note"] = OVERRIDES[r["company"]]
            status = "VERIFIED"
        if status in USABLE and ats in DIRECT:
            c["connectors"] = [{"kind": ats, "slug": r["slug"]}]
        elif status in USABLE and ats == "custom_json" and r["company"] == "Amazon":
            c["connectors"] = [{"kind": "amazon", "slug": "amazon"}]
        elif status in USABLE and ats == "eightfold" and r["company"] == "Netflix":
            c["connectors"] = [{"kind": "eightfold", "slug": "explore.jobs.netflix.net",
                                "options": {"domain": "netflix.com"}}]
        else:
            c["connectors"] = []
            c["coverage"] = "github_feed_only"
        if status == "ACQUIRED":
            c["enabled"] = False
        c["note"] = f"{ats} / {status}" + (f" — {r['note']}" if r.get("note") else "")
        companies.append(c)

    header = ("# Generated by scripts/gen_companies.py from research/source_inventory.json.\n"
              "# Add a company: append an entry with a connector kind (greenhouse | ashby | lever | workday |\n"
              "# rippling | amazon | eightfold) and its board slug. Companies with no connector are still\n"
              "# covered whenever they appear in the GitHub lists or VC boards; `aliases` are other spellings those\n"
              "# use, so the job lands in the company's tier channel.\n")
    out = ROOT / "config/companies.yaml"
    out.write_text(header + yaml.safe_dump({"companies": companies}, sort_keys=False, width=120, allow_unicode=True))
    n = sum(1 for c in companies if c["connectors"])
    print(f"wrote {out} — {len(companies)} companies, {n} with a direct connector")


if __name__ == "__main__":
    main()
